/**
 * Generates Astronaut 1's synthetic sample watch history: server/data/astronaut1-history.json
 * (Galaxy Watch shape) and server/data/astronaut1-zepp.json (Zepp OS watch shape).
 * Run with: npm run generate:sample-history -w server
 *
 * The values are generated, not recorded from anyone. They follow typical adult patterns (heart rate
 * lower at night and higher during exercise, HRV falling as heart rate rises, a slowly drifting skin
 * temperature, one main sleep a night) so the dashboard, charts and rules have realistic history to
 * show. A fixed seed makes every run produce the same files.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { DATA_DIR } from "../src/data/bundled-files.ts";

const MINUTE_MS = 60_000;
const HOUR_MS = 60 * MINUTE_MS;
const DAY_MS = 24 * HOUR_MS;
/** SI (AI) disclosure written into each file, as the NASA Space Apps rules require for generated data. */
const SI_METADATA = {
  siGenerated: true,
  generator: "server/scripts/generate-sample-history.ts (seeded; the script was written with AI tools, Anthropic Claude)",
  note: "Synthetic sample data. Not recorded from any person.",
};

const SOURCE_NOTE = "Synthetic sample data, generated by server/scripts/generate-sample-history.ts";

/** Mulberry32: a small, seeded pseudo-random generator, so the files are reproducible. */
function seeded(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = seeded(20261105);
const between = (lo: number, hi: number): number => lo + (hi - lo) * rand();
const noise = (spread: number): number => (rand() + rand() + rand() - 1.5) * spread;
const round1 = (x: number): number => Math.round(x * 10) / 10;
const round2 = (x: number): number => Math.round(x * 100) / 100;
const iso = (ms: number): string => new Date(ms).toISOString();
const clamp = (x: number, lo: number, hi: number): number => Math.min(hi, Math.max(lo, x));

/** Daytime heart rate for a minute: a daily rhythm (UTC hour, the test zone is UTC−5) plus noise. */
function restingBpm(ms: number): number {
  const localHour = (new Date(ms).getUTCHours() + 19) % 24;
  return 70 + 6 * Math.sin(((localHour - 9) / 24) * 2 * Math.PI) + noise(8);
}

// ---------- Galaxy Watch shape: worn sessions, 2026-11-05 to 2026-11-14 ----------

const GALAXY_FROM = Date.parse("2026-11-05T16:54:00.000Z");
const GALAXY_TO = Date.parse("2026-11-14T17:49:00.000Z");

interface Session { startMs: number; minutes: number; exercise: boolean }

/** The Galaxy Watch is worn on five of the ten days, so its HRV baseline (7 days) is still building. */
const GALAXY_DAYS = new Set(["2026-11-05", "2026-11-07", "2026-11-09", "2026-11-12", "2026-11-14"]);

function galaxySessions(): Session[] {
  const sessions: Session[] = [{ startMs: GALAXY_FROM, minutes: 55, exercise: false }];
  for (let day = Date.parse("2026-11-05T00:00:00.000Z"); day < GALAXY_TO; day += DAY_MS) {
    if (!GALAXY_DAYS.has(new Date(day).toISOString().slice(0, 10))) continue;
    const count = 2 + Math.floor(rand() * 3);
    for (let i = 0; i < count; i++) {
      const startMs = day + Math.round(between(14, 26 + 3) * 60) * MINUTE_MS + i * 2 * HOUR_MS;
      const exercise = i === 1 && rand() < 0.4;
      const minutes = exercise ? Math.round(between(25, 45)) : Math.round(between(10, 70));
      if (startMs > GALAXY_FROM + HOUR_MS && startMs + minutes * MINUTE_MS < GALAXY_TO - HOUR_MS) sessions.push({ startMs, minutes, exercise });
    }
  }
  sessions.push({ startMs: GALAXY_TO - 30 * MINUTE_MS, minutes: 31, exercise: false });
  return sessions.sort((a, b) => a.startMs - b.startMs);
}

function galaxyHistory() {
  const heartRate: { t: string; bpm: number; n: number }[] = [];
  const hrv: { t: string; rmssdMs: number; beats: number; pairs: number }[] = [];
  const skinTemp: { t: string; skinC: number }[] = [];
  let skin = 34.6;
  for (const s of galaxySessions()) {
    const window: number[] = [];
    for (let m = 0; m < s.minutes; m++) {
      const ms = s.startMs + m * MINUTE_MS;
      const effort = s.exercise && m > 4 && m < s.minutes - 3 ? between(45, 70) : 0;
      const bpm = clamp(restingBpm(ms) + effort, 48, 175);
      heartRate.push({ t: iso(ms), bpm: round1(bpm), n: 5 + Math.floor(rand() * 56) });
      window.push(bpm);
      if (m >= 10) {
        skin = clamp(skin + noise(0.08), 33.6, 35.4);
        skinTemp.push({ t: iso(ms + 33_000 + Math.floor(rand() * 400)), skinC: round2(skin) });
      }
      const windowEnd = (ms + MINUTE_MS) % (5 * MINUTE_MS) === 0;
      if (windowEnd && window.length >= 5) {
        const meanBpm = window.reduce((sum, x) => sum + x, 0) / window.length;
        const beats = Math.round(meanBpm * 5 * between(0.55, 0.85));
        const pairs = Math.round(beats * between(0.82, 0.93));
        const rmssd = clamp(48 - (meanBpm - 70) * 0.45 + noise(10), 14, 90);
        if (beats >= 30 && pairs >= 20) hrv.push({ t: iso(ms + MINUTE_MS - 5 * MINUTE_MS), rmssdMs: round1(rmssd), beats, pairs });
      }
      if (windowEnd) window.length = 0;
    }
  }
  return {
    source: SOURCE_NOTE + " (Galaxy Watch shape)",
    si: SI_METADATA,
    retrievedAt: "2026-11-14T17:49:13.544Z",
    units: { bpm: "beats/min, per-minute mean", rmssdMs: "ms, RMSSD per 5 min", skinC: "°C" },
    span: { from: iso(GALAXY_FROM), to: iso(GALAXY_TO) },
    heartRate, hrv, skinTemp,
  };
}

// ---------- Zepp OS watch shape: per-minute heart rate and nightly summaries, 2026-09-04 to 2026-11-14 ----------

const ZEPP_FROM = Date.parse("2026-09-04T02:20:00.000Z");
const ZEPP_TO = Date.parse("2026-11-14T20:23:00.000Z");
const LAST_NIGHT_WAKE = Date.parse("2026-11-08T14:41:00.000Z");

interface Night { sleepMs: number; wakeMs: number }

function zeppNights(): Night[] {
  const nights: Night[] = [];
  for (let day = Date.parse("2026-09-04T00:00:00.000Z"); day <= LAST_NIGHT_WAKE; day += DAY_MS) {
    if (rand() < 0.35 && day + DAY_MS <= LAST_NIGHT_WAKE) continue;
    const wakeMs = day + Math.round(between(11.5, 14.8) * 60) * MINUTE_MS;
    const sleepMs = wakeMs - Math.round(between(4.8, 8.6) * 60) * MINUTE_MS;
    nights.push({ sleepMs, wakeMs: Math.min(wakeMs, LAST_NIGHT_WAKE) });
  }
  nights[nights.length - 1] = { sleepMs: LAST_NIGHT_WAKE - Math.round(6.1 * 60) * MINUTE_MS, wakeMs: LAST_NIGHT_WAKE };
  return nights;
}

function zeppHistory(galaxyMinutes: Set<number>) {
  const nights = zeppNights();
  const asleepAt = (ms: number) => nights.some((n) => ms >= n.sleepMs && ms < n.wakeMs);
  const heartRate: { t: string; bpm: number }[] = [];
  let offWristUntil = 0;
  for (let ms = ZEPP_FROM; ms <= ZEPP_TO; ms += MINUTE_MS) {
    if (ms < offWristUntil || galaxyMinutes.has(ms)) continue;
    if (rand() < 0.0012) { offWristUntil = ms + Math.round(between(30, 150)) * MINUTE_MS; continue; }
    if (rand() < 0.35 && ms !== ZEPP_FROM && ms !== ZEPP_TO) continue;
    const bpm = asleepAt(ms) ? 57 + noise(6) : restingBpm(ms) + (rand() < 0.02 ? between(25, 55) : 0);
    heartRate.push({ t: iso(ms), bpm: Math.round(clamp(bpm, 45, 170)) });
  }
  const hrv = nights.map((n) => ({ t: iso(n.wakeMs), sleepHrvMs: Math.round(clamp(58 + noise(16), 30, 95)) }));
  const sleep = nights.map((n) => ({ t: iso(n.wakeMs), asleepH: round2(((n.wakeMs - n.sleepMs) / HOUR_MS) * between(0.82, 0.93)) }));
  const spo2 = nights.map((n) => ({ t: iso(n.wakeMs), scorePct: Math.round(clamp(96 + noise(3), 92, 100)) }));
  return {
    source: SOURCE_NOTE + " (Zepp OS watch shape)",
    si: SI_METADATA,
    device: "Zepp OS watch",
    retrievedAt: "2026-11-14T20:42:51.995Z",
    timeZone: "America/Indiana/Indianapolis",
    units: { bpm: "beats/min, per minute", sleepHrvMs: "ms, Zepp nightly sleep HRV", asleepH: "hours asleep (light + deep + REM)", scorePct: "%, Zepp nightly blood-oxygen score" },
    span: { from: iso(ZEPP_FROM), to: iso(ZEPP_TO) },
    heartRate, hrv, sleep, spo2,
  };
}

const galaxy = galaxyHistory();
const zepp = zeppHistory(new Set(galaxy.heartRate.map((r) => Date.parse(r.t))));
writeFileSync(join(DATA_DIR, "astronaut1-history.json"), JSON.stringify(galaxy));
writeFileSync(join(DATA_DIR, "astronaut1-zepp.json"), JSON.stringify(zepp));
console.log(`astronaut1-history.json: ${galaxy.heartRate.length} heart-rate minutes, ${galaxy.hrv.length} HRV windows, ${galaxy.skinTemp.length} skin temperatures`);
console.log(`astronaut1-zepp.json: ${zepp.heartRate.length} heart-rate minutes, ${zepp.sleep.length} nights`);
